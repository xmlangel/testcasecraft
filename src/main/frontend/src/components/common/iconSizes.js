// 화면 틀(상단 바·빵조각·트리 머리·사이드바)에 놓이는 아이콘 크기.
//
// 같은 줄에 크기가 다른 아이콘이 섞여 있었다. 실측하니 세 가지가 돌고 있었다 —
// 상단 바와 빵조각의 즐겨찾기·설정은 24px, 트리 머리와 보기 전환은 20px,
// 사이드바는 18px 과 20px 이 섞였다. 크기가 어긋나면 어느 것이 더 중요한 버튼인지
// 잘못 읽힌다.
//
// 18px 하나로 맞춘다. 24px 로 두면 좁은 트리 머리에서 아이콘 여섯 개가 한 줄에
// 들어가지 않고, 화면 틀의 아이콘이 본문 글자보다 커 보인다.
export const CHROME_ICON_PX = 18;

/** IconButton 안의 아이콘에 얹는 sx. 버튼 자체 크기는 각 화면이 정한다. */
export const CHROME_ICON_SX = {
  "& .MuiSvgIcon-root": { fontSize: `${CHROME_ICON_PX / 16}rem` },
};
